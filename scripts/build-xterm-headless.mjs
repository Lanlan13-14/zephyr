#!/usr/bin/env node
/**
 * Bundle @xterm/headless for the browser into public/vendor/wterm-fork/core/.
 *
 * Source of truth for forking lives at repo-root /xterm (full xterm.js tree).
 * Runtime uses published @xterm/headless (same MIT code, prebuilt).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from "fs";
import { join, dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const require = createRequire(import.meta.url);
const esbuild = require("esbuild-wasm");

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT_DIR = join(ROOT, "public", "vendor", "wterm-fork", "core");

function resolveHeadlessEntry() {
  try {
    const pkgPath = require.resolve("@xterm/headless/package.json");
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    const dir = dirname(pkgPath);
    const candidates = [
      pkg.module && join(dir, pkg.module),
      join(dir, "lib-headless", "xterm-headless.mjs"),
      join(dir, "lib-headless", "xterm-headless.js"),
      join(dir, "xterm-headless.mjs"),
      join(dir, "xterm-headless.js"),
    ].filter(Boolean);
    for (const c of candidates) {
      if (existsSync(c)) return c;
    }
  } catch (err) {
    console.error("Cannot resolve @xterm/headless — run npm install", err.message);
    process.exit(1);
  }
  console.error("No @xterm/headless entry file found");
  process.exit(1);
}

async function initEsbuild() {
  try {
    await esbuild.initialize({ worker: false });
  } catch {
    const wasmPath = require.resolve("esbuild-wasm/esbuild.wasm");
    const wasm = readFileSync(wasmPath);
    await esbuild.initialize({
      wasmModule: await WebAssembly.compile(wasm),
      worker: false,
    });
  }
}

mkdirSync(OUT_DIR, { recursive: true });
const entry = resolveHeadlessEntry();
const outfile = join(OUT_DIR, "xterm-headless.js");

console.log("==> bundling xterm headless from", entry);
await initEsbuild();
await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  outfile,
  legalComments: "inline",
  minify: false,
  logLevel: "info",
});

const registerPath = join(OUT_DIR, "xterm-headless-register.js");
writeFileSync(
  registerPath,
  `// Auto-generated by scripts/build-xterm-headless.mjs — do not edit.
import * as XtermHeadless from "./xterm-headless.js";
import { setDefaultXtermTerminalCtor } from "./xterm-bridge.js";

const Terminal = XtermHeadless.Terminal || XtermHeadless.default?.Terminal || XtermHeadless.default;
if (typeof Terminal !== "function") {
  throw new Error("xterm-headless-register: Terminal constructor missing from bundle");
}
setDefaultXtermTerminalCtor(Terminal);
export { Terminal };
export default Terminal;
`,
);

const licenseSrc = join(ROOT, "xterm", "LICENSE");
if (existsSync(licenseSrc)) {
  copyFileSync(licenseSrc, join(OUT_DIR, "XTERM-LICENSE"));
}

const size = readFileSync(outfile).byteLength;
console.log("==> wrote", outfile, `(${size} bytes)`);
console.log("==> wrote", registerPath);
