const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const src = fs.readFileSync('ai-agent-service.js', 'utf8');
const cut = src.slice(0, src.indexOf('function safeUiActionArgs'));
const sandboxRequire = (name) => {
    if (name === './ai-browser-service') return { browserService: {}, SHOT_DIR: '/tmp' };
    if (name === './ai-defaults') return { DEFAULT_ZEPHYR_SYSTEM_PROMPT: '', DEFAULT_ZEPHYR_SKILLS: [] };
    return require(name);
};
const sandbox = { require: sandboxRequire, console, URL, setTimeout, clearTimeout, DOMException, Buffer, process };
vm.createContext(sandbox);
vm.runInContext(`${cut}\nthis.__test = { normalizeContextLimits, compactConversationHistory, openAiChatTools, cachedToolDefinitions, recordAiPerf, aiPerfSnapshot };`, sandbox);
const limits = sandbox.__test.normalizeContextLimits({ context: { maxInputChars: 18000, keepMessages: 160, summaryChars: 5000, recentChars: 6000 } }, {});
const longMessages = [];
for (let i = 0; i < 80; i += 1) longMessages.push({ role: i % 2 ? 'assistant' : 'user', content: `message-${i} ` + 'x'.repeat(900) });
const compacted = sandbox.__test.compactConversationHistory(longMessages, limits);
assert(compacted.summary.includes('高轮次对话压缩摘要'));
assert(compacted.compactedCount > 0);
assert(compacted.messages.length < longMessages.length);
const toolsA = sandbox.__test.cachedToolDefinitions({ permissions: {} });
const toolsB = sandbox.__test.cachedToolDefinitions({ permissions: {} });
assert.strictEqual(toolsA, toolsB);
const convertedA = sandbox.__test.openAiChatTools(toolsA);
const convertedB = sandbox.__test.openAiChatTools(toolsA);
assert.strictEqual(convertedA, convertedB);
sandbox.__test.recordAiPerf({ status: 'ok', durationMs: 120, providerMs: 100, toolMs: 20 });
const metrics = sandbox.__test.aiPerfSnapshot();
assert(metrics.count >= 1 && metrics.avgDurationMs >= 120);
console.log(JSON.stringify({ ok: true, compactedMessages: compacted.compactedCount, kept: compacted.messages.length, summaryChars: compacted.summary.length, tools: toolsA.length, avgDurationMs: metrics.avgDurationMs }));
